#!/usr/bin/env python3
"""Candidate workspaces of the development loop: code/branches/<task>/<id>/.

    branch.py create --task T --id ID --from base|PATH/programs/<task>|branches/T/OTHER [--note TEXT]
    branch.py list [--task T] [--json]

``create`` copies the controller of the source (the incumbent's branch, the frozen program of the existing task with
the closest skill requirements, or the seed workspace base/: agraph/, runner/, runtime_params.json, tasks/__init__.py,
tasks/<T>/ and, when present, tests/) into a NEW directory branches/<T>/<ID>/ (never overwrites). When the
source has no tasks/<T>/graph.py, a skeleton package is written instead (graph.py stub that observes once
and ends, params.json, README.md describing the controller interface; see CONTROLLER_INTERFACE.md).
A source branch's NOTES.md is carried over as PARENT_NOTES.md. BRANCH.json records provenance.

A branch directory is a valid bundle for tools/queue.py enqueue --bundle branches/<T>/<ID> --branch <ID>
and tools/run_episode.py --bundle ...; only agraph/ runner/ runtime_params.json tasks/__init__.py tasks/<T>/
are frozen into a run (NOTES.md, debug/, tests/ are workspace-only).
"""
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:] = [p for p in sys.path if os.path.abspath(p or '.') != _HERE] + [_HERE]

import argparse  # noqa: E402
import json  # noqa: E402
from pathlib import Path  # noqa: E402
import re  # noqa: E402
import shutil  # noqa: E402
import stat  # noqa: E402
import time  # noqa: E402

import arconf  # noqa: E402

BRANCHES = arconf.CODE / 'branches'
COPY = ('agraph', 'runner', 'runtime_params.json', 'tasks/__init__.py', 'tests')
IGNORE = shutil.ignore_patterns('__pycache__', '*.pyc', '.pytest_cache', '.ruff_cache', '*.tmp')
ID_RE = re.compile(r'[A-Za-z0-9][A-Za-z0-9_.-]{0,63}')


def utc():
    return time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())


def resolve_source(text, task):
    """'base' | 'branches/<task>/<id>' (relative to code/) or any bundle dir, e.g. programs/<task>."""
    path = Path(text)
    if not path.is_absolute():
        path = arconf.CODE / text
    path = path.resolve()
    if not (path / 'agraph').is_dir() or not (path / 'runner').is_dir() or not (path / 'runtime_params.json').is_file():
        raise SystemExit(f'source {path} is not a controller bundle (needs agraph/ runner/ runtime_params.json)')
    return path


def _writable(root):
    for p in [root, *root.rglob('*')]:
        mode = p.stat().st_mode
        p.chmod(mode | stat.S_IWUSR | (stat.S_IXUSR if p.is_dir() else 0))


def _copy(src, dst):
    if src.is_dir():
        shutil.copytree(src, dst, ignore=IGNORE)
    elif src.is_file():
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)


STUB_GRAPH = '''"""{task}: SKELETON controller (branch.py stub). Replace with the real task graph.

Contract (CONTROLLER_INTERFACE.md): export TASK_ID == native task name and build_graph(ctx) -> Graph.
This stub takes one fresh head RGB-D frame (no motion) and ends with DONE; the harness
then holds the robot until the native action limit and the native evaluator scores the episode
(expected score 0). It exists so the whole pipeline (freeze, audit, native episode, RESULT.json) can be
exercised for {task} before any skill is written.
"""
from __future__ import annotations

from agraph.contract import ABORT, DONE, FAIL, PASS, UNKNOWN, Graph, Node, NodeResult

TASK_ID = '{task}'


def _survey(ctx):
    frame = ctx.perception.observe('stub_survey')
    ctx.facts['survey_frame'] = frame['frame']
    ctx.log('stub_survey', frame=frame['frame'], rgb=frame.get('rgb_path'),
            remaining_actions=ctx.remaining_actions(), instruction=ctx.instruction)
    return NodeResult(PASS, evidence=dict(frame=frame['frame']))


def build_graph(ctx):
    nodes = dict(survey=Node('survey', _survey, postcondition='one fresh head RGB-D frame recorded'))
    edges = dict(survey={{PASS: DONE, FAIL: ABORT, UNKNOWN: ABORT}})
    return Graph(task=TASK_ID, nodes=nodes, start='survey', edges=edges,
                 max_stagnant_visits=int(ctx.params.get('max_stagnant_visits', 4)),
                 max_transitions=int(ctx.params.get('max_transitions', 50)),
                 description='skeleton: observe once, then DONE')
'''

STUB_PARAMS = {
    '_note': 'Task tunables for {task}; frozen with the bundle and exposed as ctx.params. Keys under "skills" / '
             '"perception" override runtime_params.json for this task. The native action limit is not set here.',
    'max_stagnant_visits': 4,
    'max_transitions': 50,
    'skills': {},
    'perception': {},
}

STUB_README = '''# {task} controller skeleton (generated by branch.py)

Generated by `tools/branch.py create`: the source `{source}` has no `tasks/{task}/graph.py`, so only a skeleton is
provided here. The full interface is described in `docs/CONTROLLER_INTERFACE.md`; the essentials follow.

## Loading
- `runner/bootstrap.py` starts the native `src/eval_client/main.py --task_name {task}` and registers
  `runner/deploy.py:eval_one_episode` as the policy; the native environment calls it once after reset.
- `deploy.py` runs the static input audit (`runner/audit.py review`: every `*.py` in this bundle except `test_*.py`),
  reads the native instruction and binds it at the first observation, opens the head camera and the left/right wrist
  cameras, then calls `runner/controller.py:run_controller`.
- `run_controller` builds `ctx = TaskContext(instruction, perception, skills, agent, robot, params, facts, log)`,
  imports `tasks.{task}.graph`, requires `TASK_ID == '{task}'`, calls `build_graph(ctx)` to obtain an
  `agraph.contract.Graph` and executes it with `GraphExecutor.run(ctx)`.
- `params.json` is `ctx.params`; its `skills` / `perception` keys override the parameters of the same name in
  `runtime_params.json`.

## Nodes and termination
- A node is `Node(name, run, ready=..., postcondition=..., requires=())` with `run(ctx) -> NodeResult(PASS|FAIL|UNKNOWN,
  cause, evidence, actions)`; `edges[name] = {{PASS: next node, FAIL: ..., UNKNOWN: ...}}`; a target may be `DONE` or `ABORT`.
- The controller ends on `DONE` / `ABORT`, when the action budget is exhausted (`BudgetExhausted`), or when
  `max_stagnant_visits` / `max_transitions` trigger. The controller never declares success; afterwards the harness holds
  the robot in place until the native action limit `step_lim` and the native evaluator scores the episode.
- Tasks that require both arms back at their origin with open grippers for full score must call `ctx.skills.home()`
  themselves before `DONE`.

## Available inputs (only these)
- `ctx.instruction` (native instruction text)
- `ctx.perception`: `observe(stage)`, `observe_wrist(arm, stage)` (fresh simulator RGB-D frame from the official
  observation: RGB, depth image, intrinsics, camera pose); SAM 3 segmentation through `agraph/local_vision.py`
- `ctx.robot`: `tcp(arm)`, `base_transform(arm)`, `action_count`, `action_limit` (encoders + URDF forward kinematics)
- `ctx.skills`: `pick / place / transport / push / release / retreat / home / verify_held / reachable / plan_route ...`
- `ctx.log(event, **kw)` writes `trace.jsonl`

Forbidden: simulator state, `Assets/`, layout JSON, `task/RoboDojo/config|tasks`, native results; no `import env/task/src`;
audit-blacklisted words such as `success`, `seed_info`, `scene_layout` must not appear in `.py` files (see
`runner/audit.py`). Offline debugging tools go under the workspace `debug/` directory and must never be imported at run time.
'''


def skeleton(dst, task, source):
    pkg = dst / 'tasks' / task
    pkg.mkdir(parents=True, exist_ok=True)
    (pkg / '__init__.py').write_text('')
    (pkg / 'graph.py').write_text(STUB_GRAPH.format(task=task))
    params = {k: (v.format(task=task) if isinstance(v, str) else v) for k, v in STUB_PARAMS.items()}
    (pkg / 'params.json').write_text(json.dumps(params, indent=2, ensure_ascii=False) + '\n')
    (pkg / 'README.md').write_text(STUB_README.format(task=task, source=source))


NOTES = '''# {task} / {bid} branch notes

- Created: {created}, from `{source}`{skeleton}
- Note: {note}

Append after every iteration: hypothesis, change, per-layout results (score, success, actions, wall time), what was
learned. After a flush, the new agent continues from here (these notes are the only memory across sessions).

## Iteration log
'''


def cmd_create(a):
    if a.task not in arconf.TASKS:
        raise SystemExit(f'unknown task {a.task}; tasks: {", ".join(arconf.TASKS)}')
    if not ID_RE.fullmatch(a.id):
        raise SystemExit(f'bad branch id {a.id!r} (letters, digits, _ . -; max 64)')
    src = resolve_source(a.source, a.task)
    dst = BRANCHES / a.task / a.id
    if dst.exists():
        raise SystemExit(f'{dst} already exists; branch ids are never reused')
    staging = dst.with_name(f'.{a.id}.staging')
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)
    for rel in COPY:
        _copy(src / rel, staging / rel)
    if not (staging / 'tasks' / '__init__.py').exists():
        (staging / 'tasks').mkdir(exist_ok=True)
        (staging / 'tasks' / '__init__.py').write_text('')
    has_graph = (src / 'tasks' / a.task / 'graph.py').is_file()
    if has_graph:
        _copy(src / 'tasks' / a.task, staging / 'tasks' / a.task)
    else:
        skeleton(staging, a.task, a.source)
    if (src / 'NOTES.md').is_file():
        shutil.copy2(src / 'NOTES.md', staging / 'PARENT_NOTES.md')
    (staging / 'debug').mkdir(exist_ok=True)
    _writable(staging)
    sys.path.insert(0, str(arconf.BASE))
    from agraph import candidates  # base/agraph (same manifest rule the freezer uses)
    sha = candidates.manifest(staging, a.task)['source_sha256']
    parent_meta = {}
    if (src / 'BRANCH.json').is_file():
        parent_meta = json.loads((src / 'BRANCH.json').read_text())
    record = dict(task=a.task, id=a.id, source=a.source, source_path=str(src), skeleton=not has_graph,
                  parent_branch=parent_meta.get('id'), created_utc=utc(), created_host=os.uname().nodename,
                  note=a.note, initial_bundle_sha256=sha)
    (staging / 'BRANCH.json').write_text(json.dumps(record, indent=2, ensure_ascii=False) + '\n')
    (staging / 'NOTES.md').write_text(NOTES.format(task=a.task, bid=a.id, created=record['created_utc'],
                                                   source=a.source, note=a.note or '—',
                                                   skeleton=' (source had no graph for this task; skeleton generated)' if not has_graph else ''))
    os.rename(staging, dst)
    print(json.dumps(dict(created=str(dst), skeleton=not has_graph, initial_bundle_sha256=sha), ensure_ascii=False))


def branch_dirs(task=None):
    tasks = [task] if task else sorted(p.name for p in BRANCHES.iterdir() if p.is_dir()) if BRANCHES.is_dir() else []
    for t in tasks:
        root = BRANCHES / t
        if root.is_dir():
            for d in sorted(root.iterdir()):
                if d.is_dir() and not d.name.startswith('.'):
                    yield t, d


def _results():
    path = arconf.STATE / 'results.jsonl'
    rows = []
    if path.exists():
        rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    return rows


def cmd_list(a):
    sys.path.insert(0, str(arconf.BASE))
    from agraph import candidates
    rows = _results()
    out = []
    for task, d in branch_dirs(a.task):
        meta = json.loads((d / 'BRANCH.json').read_text()) if (d / 'BRANCH.json').is_file() else {}
        try:
            sha = candidates.manifest(d, task)['source_sha256'] if (d / 'tasks' / task / 'graph.py').is_file() else None
        except Exception as exc:  # unreadable bundle is reported, not fatal
            sha = f'error: {exc}'
        mine = [r for r in rows if r.get('task') == task and r.get('branch') == d.name and not r.get('superseded')]
        out.append(dict(task=task, id=d.name, source=meta.get('source'), skeleton=meta.get('skeleton'),
                        created_utc=meta.get('created_utc'), bundle_sha256=sha,
                        modified=bool(sha and meta.get('initial_bundle_sha256') and sha != meta['initial_bundle_sha256']),
                        episodes=len(mine), verified=sum(r.get('status') == 'verified' for r in mine),
                        successes=sum(bool(r.get('success')) for r in mine if r.get('status') == 'verified'),
                        note=meta.get('note')))
    if a.json:
        print(json.dumps(out, indent=1, ensure_ascii=False))
        return
    for r in out:
        print(f"{r['task']:<30} {r['id']:<20} from={r['source']:<22} sha={str(r['bundle_sha256'])[:12]} "
              f"{'modified' if r['modified'] else 'pristine':<8} episodes={r['episodes']} verified={r['verified']} "
              f"succ={r['successes']}{' skeleton' if r['skeleton'] else ''}")
    if not out:
        print('no branches')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    c = sub.add_parser('create')
    c.add_argument('--task', required=True)
    c.add_argument('--id', required=True)
    c.add_argument('--from', dest='source', required=True, help='base | branches/<task>/<id> | path to a bundle such as programs/<task>')
    c.add_argument('--note', default=None)
    c.set_defaults(fn=cmd_create)
    s = sub.add_parser('list')
    s.add_argument('--task')
    s.add_argument('--json', action='store_true')
    s.set_defaults(fn=cmd_list)
    a = ap.parse_args()
    a.fn(a)


if __name__ == '__main__':
    main()
